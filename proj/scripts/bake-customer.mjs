#!/usr/bin/env node
/**
 * 고객(안전사고) 집계 재생성: src/data/raw/customer_accidents.json → src/data/customerData.js
 *
 * computeCustomer.js(순수함수)에 원시 JSON을 주입해 집계 결과를 baked const로 write.
 * 원시 1.5MB JSON을 클라 번들에 넣지 않기 위한 기존 전략 유지.
 *
 * Usage: cd proj && node scripts/bake-customer.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { computeCustomer } from '../src/utils/computeCustomer.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const RAW = resolve(__dirname, '..', 'src', 'data', 'raw', 'customer_accidents.json');
const OUT = resolve(__dirname, '..', 'src', 'data', 'customerData.js');

const raw = JSON.parse(readFileSync(RAW, 'utf-8'));
const data = computeCustomer(raw.data);

const out =
  `// === Auto-generated by scripts/bake-customer.mjs — 수동수정 금지 ===\n` +
  `// 고객 안전사고 집계(원인1→2→3 정규화·원인3/교차 포함). 갱신: node scripts/bake-customer.mjs\n` +
  `const CUSTOMER_DATA = ${JSON.stringify(data)};\nexport default CUSTOMER_DATA;\n`;

writeFileSync(OUT, out, 'utf-8');
console.log(`✔ customerData.js 재생성 완료`);
console.log(`  총 ${data.kpis_all.total}건 · 사고유형 ${data.types.length}종 · 원인1 ${data.causes1.length} · 원인3 ${data.causes3.length}`);
console.log(`  typeCause ${data.typeCause.all.length}×${data.typeCause.cols.length} · causeAction ${data.causeAction.all.length}×${data.causeAction.cols.length}`);
